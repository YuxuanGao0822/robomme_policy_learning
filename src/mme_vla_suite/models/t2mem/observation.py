"""Identical robot preprocessing, with model-specific routing of proprioception.

The native memory-free pi0.5 consumes a discretized-state language prefix.
T²Mem consumes instruction-only VL features and a continuous proprioceptive
suffix, keeping its memory interface observation-grounded. Both tokenizations
are generated by the same transform and supplied to every experimental model.
"""

from dataclasses import dataclass

from flax import struct
import numpy as np

from openpi.models.model import Observation


@struct.dataclass
class T2Observation(Observation):
    tokenized_pi05_prompt: object = None
    tokenized_pi05_prompt_mask: object = None

    @classmethod
    def from_dict(cls, data):
        base = Observation.from_dict(data)
        if ("tokenized_pi05_prompt" in data) != ("tokenized_pi05_prompt_mask" in data):
            raise ValueError("The native pi05 prompt and validity mask must be supplied together")
        return cls(
            images=base.images, image_masks=base.image_masks, state=base.state,
            tokenized_prompt=base.tokenized_prompt, tokenized_prompt_mask=base.tokenized_prompt_mask,
            token_ar_mask=base.token_ar_mask, token_loss_mask=base.token_loss_mask,
            tokenized_pi05_prompt=data.get("tokenized_pi05_prompt"),
            tokenized_pi05_prompt_mask=data.get("tokenized_pi05_prompt_mask"),
        )


@dataclass(frozen=True)
class TokenizeT2MemPrompt:
    tokenizer: object

    def __call__(self, data):
        if "prompt" not in data or "state" not in data:
            raise ValueError("T²Mem tokenization requires instruction and normalized robot state")
        data = dict(data)
        prompt = data.pop("prompt")
        if isinstance(prompt, np.ndarray):
            prompt = prompt.item()
        native, native_mask = self.tokenizer.tokenize(str(prompt), data["state"])
        vl, vl_mask = self.tokenizer.tokenize(str(prompt))
        data["tokenized_pi05_prompt"], data["tokenized_pi05_prompt_mask"] = native, native_mask
        data["tokenized_prompt"], data["tokenized_prompt_mask"] = vl, vl_mask
        return data
